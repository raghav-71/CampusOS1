import { NextResponse } from 'next/server';
import type { NextRequest } from 'next/server';
import { providerChain } from '@/lib/ai/provider/providerChain';
import { AIQuestionPaper } from '@/lib/ai/aiTypes';

export async function POST(request: NextRequest) {
  try {
    const {
      subject,
      topics,
      difficulty = 'Moderate',
      totalMarks = 100,
      semester = 'Semester 5',
      questionTypes = 'Short conceptual, Algorithmic design, Numerical analysis',
      customInstructions = '',
    } = await request.json();

    const marks = Number(totalMarks) || 100;
    const diff = difficulty || 'Moderate';
    const sub = subject || 'Operating Systems (CS501)';
    const sem = semester || 'Semester 5';
    const top = topics || 'Process Management, Deadlocks, Paging, Memory Allocation, CPU Scheduling';

    const partAMarks = marks === 100 ? 20 : marks === 50 ? 10 : 5;
    const partBMarks = marks - partAMarks;
    const duration = marks === 100 ? '3 Hours' : marks === 50 ? '90 Minutes' : '45 Minutes';

    const prompt = `Generate a genuine, brand-new university examination paper matching these exact specifications:
Course / Subject: ${sub}
Semester: ${sem}
Syllabus Units & Topics: ${top}
Difficulty: ${diff}
Total Marks: ${marks}
Duration: ${duration}
Question Types: ${questionTypes}
${customInstructions ? `Additional Teacher Guidance: ${customInstructions}` : ''}

Structure Requirements:
1. Section A: Short answer, fundamental definitions, and core conceptual questions (${partAMarks} marks total).
2. Section B: Analytical, algorithmic problem-solving, numerical derivations, and architectural design questions (${partBMarks} marks total).
3. Detailed Step-by-Step Scoring Rubrics & Answer Key for professors.

Do NOT return placeholder questions. Generate challenging, realistic, syllabus-aligned university questions.`;

    const schemaHint = `{
  "title": "${sub} — Examination Assessment (${diff})",
  "subject": "${sub}",
  "semester": "${sem}",
  "difficulty": "${diff}",
  "totalMarks": ${marks},
  "duration": "${duration}",
  "instructions": [
    "Answer all questions in Section A.",
    "Answer any four comprehensive questions in Section B.",
    "Calculators and standard mathematical tables are permitted."
  ],
  "sections": [
    {
      "name": "Section A (Short Conceptual Questions — ${partAMarks} Marks)",
      "instructions": "Answer all questions. Each question carries 4 marks.",
      "totalSectionMarks": ${partAMarks},
      "questions": [
        "1. [Question 1 text here]",
        "2. [Question 2 text here]",
        "3. [Question 3 text here]",
        "4. [Question 4 text here]",
        "5. [Question 5 text here]"
      ]
    },
    {
      "name": "Section B (Analytical & Problem-Solving — ${partBMarks} Marks)",
      "instructions": "Answer all comprehensive problem scenarios.",
      "totalSectionMarks": ${partBMarks},
      "questions": [
        "6. (a) [Sub-question] (b) [Sub-question]",
        "7. [Numerical problem with specific dataset]",
        "8. [Algorithmic analysis question]",
        "9. [System architecture & design scenario]"
      ]
    }
  ],
  "answerKey": {
    "rubrics": [
      "Section A: 2 marks for standard definition/axiom, 2 marks for neat diagram/formula.",
      "Section B: Step-by-step mathematical derivation (5 marks), algorithm correctness (5 marks), analysis (5 marks)."
    ]
  }
}`;

    const systemPrompt =
      'You are a senior university examination board member and computer science curriculum designer. Generate genuine, syllabus-accurate examination question papers formatted strictly as JSON.';

    try {
      const generatedPaper = await providerChain.generateStructured<AIQuestionPaper>(
        prompt,
        systemPrompt,
        schemaHint
      );

      if (!generatedPaper || !generatedPaper.sections || generatedPaper.sections.length === 0) {
        throw new Error('Incomplete paper generated by provider.');
      }

      return NextResponse.json({ paper: generatedPaper, success: true });
    } catch (llmErr: any) {
      // If AI provider is offline or failed, return honest error
      return NextResponse.json(
        {
          success: false,
          error:
            'AI Question Paper Generation requires an active AI provider. Please configure OPENROUTER_API_KEY in your .env file to enable live LLM generation.',
          details: llmErr.message,
        },
        { status: 503 }
      );
    }
  } catch (err: any) {
    console.error('Generate Paper Route Error:', err);
    return NextResponse.json({ error: err.message, success: false }, { status: 500 });
  }
}
