/**
 * Remote Free AI Provider: Google Gemini
 * High-speed inference using Google AI Gemini 1.5 Flash / 2.0 Flash REST API.
 */

import {
  AIProvider,
  LLMMessage,
  LLMCompletionOptions,
  LLMCompletionResult,
  LLMStreamChunk,
} from './types';

const CANDIDATE_GEMINI_MODELS = [
  process.env.GEMINI_MODEL || 'gemini-1.5-flash',
  'gemini-2.0-flash-exp',
  'gemini-1.5-pro',
];

export class GeminiProvider implements AIProvider {
  name = 'Google Gemini (Free Tier)';
  private apiKey: string;
  private defaultModel: string;

  constructor(apiKey?: string, defaultModel?: string) {
    this.apiKey = apiKey || process.env.GEMINI_API_KEY || process.env.GOOGLE_API_KEY || '';
    this.defaultModel = defaultModel || CANDIDATE_GEMINI_MODELS[0];
  }

  private getCleanKey(): string {
    return (
      this.apiKey ||
      process.env.GEMINI_API_KEY ||
      process.env.GOOGLE_API_KEY ||
      ''
    ).trim();
  }

  isConfigured(): boolean {
    const key = this.getCleanKey();
    return Boolean(key) && !key.includes('your-gemini-key') && key.length > 10;
  }

  async isAvailable(): Promise<boolean> {
    if (!this.isConfigured()) return false;
    try {
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 3000);
      const res = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models?key=${this.getCleanKey()}`,
        { signal: controller.signal }
      );
      clearTimeout(timeoutId);
      return res.ok;
    } catch {
      return false;
    }
  }

  async getAvailableModels(): Promise<string[]> {
    return CANDIDATE_GEMINI_MODELS;
  }

  async chatCompletion(
    messages: LLMMessage[],
    options?: LLMCompletionOptions
  ): Promise<LLMCompletionResult> {
    if (!this.isConfigured()) {
      throw new Error('Gemini provider is not configured. GEMINI_API_KEY is missing.');
    }

    const key = this.getCleanKey();
    const model = options?.model || process.env.GEMINI_MODEL || CANDIDATE_GEMINI_MODELS[0];

    // Convert messages to Gemini API format
    const contents = messages
      .filter((m) => m.role !== 'system')
      .map((m) => ({
        role: m.role === 'assistant' ? 'model' : 'user',
        parts: [{ text: m.content || '' }],
      }));

    const systemInstruction = messages.find((m) => m.role === 'system')?.content;

    const payload: Record<string, any> = {
      contents,
      generationConfig: {
        temperature: options?.temperature ?? 0.2,
        maxOutputTokens: options?.maxTokens ?? 3000,
      },
    };

    if (systemInstruction) {
      payload.systemInstruction = {
        parts: [{ text: systemInstruction }],
      };
    }

    const startTime = Date.now();
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 22000);

    try {
      const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${key}`;
      const res = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload),
        signal: options?.signal || controller.signal,
      });

      clearTimeout(timeoutId);

      if (!res.ok) {
        const err = await res.json().catch(() => ({}));
        throw new Error(
          err.error?.message || `Google Gemini returned status HTTP ${res.status}`
        );
      }

      const data = await res.json();
      const text =
        data.candidates?.[0]?.content?.parts?.[0]?.text ||
        'No response generated by model.';

      return {
        text,
        modelUsed: model,
        provider: this.name,
        durationMs: Date.now() - startTime,
      };
    } finally {
      clearTimeout(timeoutId);
    }
  }
}

export const geminiProvider = new GeminiProvider();
